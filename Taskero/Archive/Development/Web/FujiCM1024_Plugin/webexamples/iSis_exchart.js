// if you have copied it to a temporary to pass down to the plugin. 

// We have to use a function to copy the object, otherwise it uses the same
// referenche and future changes to "patch" changes all members of the array
function setpatch(patcharray, patch) 
{
    var tpatch = new Object();
    tpatch["SampleName"] = patch["SampleName"];
    tpatch["HTMLColor"] = patch["HTMLColor"];
    tpatch["SampleID"] = patch["SampleID"]; 
    patcharray.push(tpatch);
}

