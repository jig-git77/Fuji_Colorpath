
IF EXISTS (SELECT * FROM sysobjects WHERE type = 'P' AND name = 'uspDeleteMeasurementByGUIDs')
	BEGIN
		DROP  Procedure [CPV].[uspDeleteMeasurementByGUIDs]
	END

GO
/*
AUTHOR : Jignesh Patel
Created Date : Aug 18 2008

Purpose : Delete Mesurement .
Instruction : @CPMeasurementGUID should be in below given format.
28849A78-113E-11DD-89C5-000A958F3FC6,28849A78-113E-11DD-89C5-000A958F3FC6,28849A78-113E-11DD-89C5-000A958F3FC6
*/
CREATE PROCEDURE [CPV].[uspDeleteMeasurementByGUIDs]( @CPMeasurementGUID VARCHAR(8000) ) 
AS  
BEGIN
	BEGIN TRY

		/*---------- ASSIGN TO XML --- -------*/
		DECLARE @xmlCPMeasurementGUID XML	
		SET @xmlCPMeasurementGUID = '<GUIDs><GUID>' + REPLACE( @CPMeasurementGUID , ',' , '</GUID><GUID>' ) + '</GUID></GUIDs>'
		
		DELETE
		FROM CPMeasurement
		WHERE CPMeasurementGUID IN (
										SELECT xmlCPMeasurementGUID.value('.', 'VARCHAR(36)') AS GUID 
										FROM @xmlCPMeasurementGUID.nodes('/GUIDs/GUID') d(xmlCPMeasurementGUID)
									)
		
		END TRY
	BEGIN CATCH
		DECLARE @ERROR_NUMBER INT 
		DECLARE @ERROR_SEVERITY INT
		DECLARE @ERROR_STATE INT 
		DECLARE @ERROR_PROCEDURE NVARCHAR(252) 
		DECLARE @ERROR_LINE INT 
		DECLARE @ERROR_MESSAGE NVARCHAR(4000) 
		SELECT @ERROR_NUMBER = ERROR_NUMBER()  , @ERROR_NUMBER = ERROR_NUMBER() , @ERROR_SEVERITY = ERROR_SEVERITY() , @ERROR_STATE = ERROR_STATE() , @ERROR_PROCEDURE = ERROR_PROCEDURE() , @ERROR_LINE = ERROR_LINE() , @ERROR_MESSAGE = ERROR_MESSAGE() 
		EXEC CPV.uspInsertSQLErrorLog @ERROR_NUMBER , @ERROR_SEVERITY , @ERROR_STATE , @ERROR_PROCEDURE , @ERROR_LINE , @ERROR_MESSAGE 
	END CATCH
END 