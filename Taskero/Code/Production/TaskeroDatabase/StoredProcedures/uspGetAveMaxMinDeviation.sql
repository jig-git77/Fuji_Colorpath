IF EXISTS (SELECT * FROM sysobjects WHERE type = 'P' AND name = 'uspGetAveMaxMinDeviation')
	BEGIN
		DROP  Procedure  [CPV].[uspGetAveMaxMinDeviation]
	END
GO
/*  
AUTHOR : Maulik Dhorajia
Created Date : Aug 4 2008  
Purpose : Gets the Ave, Max & Min Deviation on GUID.  
*/
CREATE PROCEDURE [CPV].[uspGetAveMaxMinDeviation] ( @MeasurementGUID VARCHAR(50) )
AS    
BEGIN  
	BEGIN TRY

		SELECT 
			ISNULL( CONVERT( DECIMAL(18,2) , AVG(ABS(DEVIATION)) ) , 0 )  AS AveD
			, ISNULL( CONVERT( DECIMAL(18,2) , MAX(DEVIATION) ) , 0 )  AS MaxD
			, ISNULL( CONVERT( DECIMAL(18,2) , MIN(DEVIATION) ) , 0 )  AS MinD
		FROM CPPatchDataPlate 
		WHERE MeasurementGUID = @MeasurementGUID

	END TRY  
	BEGIN CATCH  
		DECLARE @ERROR_NUMBER INT   
		DECLARE @ERROR_SEVERITY INT  
		DECLARE @ERROR_STATE INT   
		DECLARE @ERROR_PROCEDURE NVARCHAR(252)   
		DECLARE @ERROR_LINE INT   
		DECLARE @ERROR_MESSAGE NVARCHAR(4000)   
		SELECT @ERROR_NUMBER = ERROR_NUMBER()  , @ERROR_NUMBER = ERROR_NUMBER() , @ERROR_SEVERITY = ERROR_SEVERITY() , @ERROR_STATE = ERROR_STATE() , @ERROR_PROCEDURE = ERROR_PROCEDURE() , @ERROR_LINE = ERROR_LINE() , @ERROR_MESSAGE = ERROR_MESSAGE()   
		EXEC CPV.uspInsertSQLErrorLog @ERROR_NUMBER , @ERROR_SEVERITY , @ERROR_STATE , @ERROR_PROCEDURE , @ERROR_LINE , @ERROR_MESSAGE   
	END CATCH  
END
