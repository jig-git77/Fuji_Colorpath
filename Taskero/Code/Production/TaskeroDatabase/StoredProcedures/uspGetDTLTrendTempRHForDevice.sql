IF EXISTS (SELECT * FROM sysobjects WHERE type = 'P' AND name = 'uspGetDTLTrendTempRHForDevice')
	BEGIN
		DROP  Procedure [CPV].[uspGetDTLTrendTempRHForDevice]
	END

GO

/*
AUTHOR : Maulik Dhorajia
Created Date : July 19 2008
Purpose : Gets the temperature on device.

*/
CREATE PROCEDURE [CPV].[uspGetDTLTrendTempRHForDevice]
( 
	@CPDeviceID INT 
) 
AS  
BEGIN
	BEGIN TRY

		SELECT 
			TOP 50 TempF , RH , CreatedDt 
		FROM 
			TempRHDevice_CPDevice
		INNER JOIN TempRHData ON TempRHDevice_CPDevice.TempRHDeviceID = TempRHData.TempRHDeviceID
		WHERE 
			CPDeviceID = @CPDeviceID
		ORDER BY 
			CreatedDt 
		DESC

	END TRY
	BEGIN CATCH
		DECLARE @ERROR_NUMBER INT 
		DECLARE @ERROR_SEVERITY INT
		DECLARE @ERROR_STATE INT 
		DECLARE @ERROR_PROCEDURE NVARCHAR(252) 
		DECLARE @ERROR_LINE INT 
		DECLARE @ERROR_MESSAGE NVARCHAR(4000) 
		SELECT @ERROR_NUMBER = ERROR_NUMBER()  , @ERROR_NUMBER = ERROR_NUMBER() , @ERROR_SEVERITY = ERROR_SEVERITY() , @ERROR_STATE = ERROR_STATE() , @ERROR_PROCEDURE = ERROR_PROCEDURE() , @ERROR_LINE = ERROR_LINE() , @ERROR_MESSAGE = ERROR_MESSAGE() 
		EXEC CPV.uspInsertSQLErrorLog @ERROR_NUMBER , @ERROR_SEVERITY , @ERROR_STATE , @ERROR_PROCEDURE , @ERROR_LINE , @ERROR_MESSAGE 
	END CATCH
END
