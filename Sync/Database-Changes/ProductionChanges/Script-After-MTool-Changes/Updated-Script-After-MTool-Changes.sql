	DECLARE @D0_M	   Decimal(9,5)	 --Density of paper white using green filter
	DECLARE @D0_Y	   Decimal(9,5)	 --Density of paper white using blue filter
	DECLARE @D0		   Decimal(9,5)	 --Density of paper white using visual filter

	DECLARE @D100_C	   Decimal(9,5)	 --Density of Solid Cyan Patch
	DECLARE @D100_M	   Decimal(9,5)	 --Density of Solid Magenta Patch
	DECLARE @D100_Y	   Decimal(9,5)   --Density of Solid Yellow  Patch
	DECLARE @D100_K	   Decimal(9,5)   --Density of Solid Black   Patch 


	IF EXISTS (SELECT TOP 1 * FROM CPSync.MeasurementPatch WHERE MeasurementID= @MeasurementID)  

		BEGIN

			--Density of White Paper Patch (Visual filter)
			SELECT  @D0 = ISNULL(MP.Density_V,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 8		

			--Density of paper white  red filter 
			SELECT  @D0_C = ISNULL(MP.Density_C,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 8		

			--Density of paper white using green filter
			SELECT  @D0_M = ISNULL(MP.Density_M,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 8		

			--Density of paper white using blue filter
			SELECT  @D0_Y = ISNULL(MP.Density_Y,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 8		


			--Find density of 100% Cyan Dot
			SELECT  @D100_C = ISNULL(MP.Density_C,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 1		

			--Find density of 100% Magenta Dot
			SELECT  @D100_M = ISNULL(MP.Density_M,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 2		

			--Find density of 100% Yellow Dot 
			SELECT  @D100_Y = ISNULL(MP.Density_Y,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 3			
	 
			--Find density of 100% Key(Black) Dot
			SELECT  @D100_K = ISNULL(MP.Density_V,0) FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID = 4		

			--using Common table expression

			;WITH  Cyan  --find all Cyan Screens 
			AS
			 (
				SELECT MP.MeasurementPatchID, RC.CMYK_C, AVG(MP.Density_C) As Density FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID  in (12,16,17,18,112,113,114,115,116,117,118,119,120,121,122) AND MP.Density_C <> 0 GROUP BY MP.MeasurementPatchID, RC.CMYK_C 
			 )

			 INSERT INTO CPSync.MeasuredColorChar  ([MeasurementPatchID],[ColorCharID],[ColorCharValue])
				SELECT MeasurementPatchID , 9 , COALESCE(CP.fn_CalcDotGain(@D0_C,@D100_C,CYAN.Density,CMYK_C),0) As DotGain	FROM CYAN


			 --using Common table expression

			;WITH  Magenta --find all Magenta Screens 
			AS
			 (
				SELECT MP.MeasurementPatchID,RC.CMYK_M, AVG(MP.Density_M) As Density FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID  in (13,19,20,21,123,124,125,126,127,128,129,130,131,132,133) AND MP.Density_M IS NOT NULL AND MP.Density_M <> 0 GROUP BY MP.MeasurementPatchID, RC.CMYK_M 
			 )

			 INSERT INTO CPSync.MeasuredColorChar  ([MeasurementPatchID],[ColorCharID],[ColorCharValue])
				SELECT MeasurementPatchID ,9 , COALESCE(CP.fn_CalcDotGain(@D0_M,@D100_M,Magenta.Density,CMYK_M),0) As DotGain FROM Magenta


			 --using Common table expression

			;WITH  Yellow --find all Yellow Screens 
			AS
			 (
				SELECT MP.MeasurementPatchID, RC.CMYK_Y, AVG(MP.Density_Y) As Density FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
			    WHERE M.MeasurementID = @MeasurementID AND RC.PatchtypeID  in (14,22,23,24,134,135,136,137,138,139,140,141,142,143,144) AND MP.Density_Y IS NOT NULL AND MP.Density_Y <> 0 GROUP BY MP.MeasurementPatchID, RC.CMYK_Y 
			 )

			 INSERT INTO CPSync.MeasuredColorChar  ([MeasurementPatchID],[ColorCharID],[ColorCharValue])
				SELECT  MeasurementPatchID , 9 , COALESCE(CP.fn_CalcDotGain(@D0_Y,@D100_Y,Yellow.Density,CMYK_Y),0) As DotGain FROM Yellow


			 --using Common table expression
	 
			;WITH  Black --find all Black Screens
			 AS
			 (
 				SELECT MP.MeasurementPatchID,RC.CMYK_K, AVG(MP.Density_V) As Density FROM CPSync.MeasurementPatch AS MP INNER JOIN
				CPSync.Measurement AS M ON M.MeasurementID = MP.MeasurementID INNER JOIN
				CP.ReferenceChart AS RC ON RC.ChartTypeID = M.ReferenceChartTypeID AND RC.SampleName = MP.SampleName
