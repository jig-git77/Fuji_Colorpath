ALTER PROCEDURE [CPSync].[CreateMeasurement]
	@MeasurementName NVARCHAR(50),
	@OptimizeRunID INT,
	@MeasurementDate DATETIME,
	@ReferenceChartTypeID TINYINT,
	@MeasurementPatches XML,
	@MeasurementID INT OUTPUT,
	@PCSDataType INT = 1,
	@UserID INT,
	@MeasurementInfo  NVARCHAR(500)
AS
	BEGIN TRY	
		BEGIN TRAN
			DECLARE @MTPID smallInt;
			DECLARE @ProjectID INT;

			SELECT @ProjectID = ProjectID from CPSync.OptimizeRun where OptimizeRunID = @OptimizeRunID

			SELECT @MTPID = MetricTargetPresetID from CPSync4D.Project where ProjectID = @ProjectID
				
			INSERT INTO CPSync.Measurement
				(
					MeasurementName,
					OptimizeRunID,
					MeasurementDate,
					ReferenceChartTypeID,
					IsUsed,
					MetricTargetPresetID,
					IsOK,
					MeasurementInfo
				)
			VALUES
				(
					@MeasurementName,
					@OptimizeRunID,
					@MeasurementDate,
					@ReferenceChartTypeID,
					1,
					@MTPID,
					0,
					@MeasurementInfo
				)
				
			SET @MeasurementID = @@IDENTITY

			EXEC [CPSync].[CreateMeasurementPatches] @PCSDataType,@MeasurementPatches,@MeasurementID 

			-------Update LastActiveDate for Project as Today's date-------
			UPDATE [CPSync4D].[Project] SET LastActiveDate = GETDATE() WHERE ProjectID = @ProjectID

		COMMIT TRAN	
		
		-----Separate two transactions so even if metric caluclations fails still it will make measurement entry as bad measurement into tables-----	
		
		BEGIN TRAN			
			
			---INSERT DOTGAIN VALUES INTO CPSync.MeasuredColorChar TABLE
			EXEC [CPSync].[uspInsertColorCharDotGain] @MeasurementID,@UserID

			
			---INSERT ?Ch VALUES INTO CPSync.MeasuredColorChar TABLE
			EXEC [CPSync].[uspInsertColorChar?Ch] @MeasurementID,@UserID
			---INSERT ?L VALUES INTO CPSync.MeasuredColorChar TABLE
			EXEC [CPSync].[uspInsertColorChar?L] @MeasurementID,@UserID

			--------Set Metrics----------------			
			EXEC [CPSync].[CalculateMetrics] @MeasurementID,@UserID
											
			-----Update IsOk entry onto CPSync.Measurement table-------
			UPDATE CPSync.Measurement SET IsOK = 1 WHERE MeasurementID = @MeasurementID

			-----Delete From dbo.MeasurementError_File table if ISOK =1 ---
			DELETE FROM dbo.MeasurementError_File WHERE OptimizationRunID=@OptimizeRunID AND ProjectID=@ProjectID

		COMMIT TRAN
	END TRY
	BEGIN CATCH
		ROLLBACK TRAN
		DECLARE @ERROR_NUMBER INT 
		DECLARE @ERROR_SEVERITY INT
		DECLARE @ERROR_STATE INT 
		DECLARE @ERROR_PROCEDURE NVARCHAR(252) 
		DECLARE @ERROR_LINE INT 
		DECLARE @ERROR_MESSAGE NVARCHAR(4000) 
		SELECT @ERROR_NUMBER = ERROR_NUMBER()  , @ERROR_NUMBER = ERROR_NUMBER() , @ERROR_SEVERITY = ERROR_SEVERITY() , @ERROR_STATE = ERROR_STATE() , @ERROR_PROCEDURE = ERROR_PROCEDURE() , @ERROR_LINE = ERROR_LINE() , @ERROR_MESSAGE = ERROR_MESSAGE() 		
		EXEC InsertSQLErrorLog @ERROR_NUMBER , @ERROR_SEVERITY , @ERROR_STATE , @ERROR_PROCEDURE , @ERROR_LINE , @ERROR_MESSAGE 		
		--EXEC [dbo].[CreateMeasurementLog] @UserID,@MeasurementID,'Error in Sync1D project measurement',@ERROR_MESSAGE,'Sync1D'
		SET @MeasurementID = -1
		RAISERROR(@ERROR_MESSAGE,@ERROR_SEVERITY,@ERROR_STATE) /******Raise Error backto client *****/ 
	END CATCH
GO
