			 )

			 INSERT INTO CPSync.MeasuredColorChar  ([MeasurementPatchID],[ColorCharID],[ColorCharValue]) 
				SELECT MeasurementPatchID ,  9, COALESCE(CP.fn_CalcDotGain(@D0,@D100_K,Black.Density,CMYK_K),0) As DotGain FROM Black 
		 
		 END
		 

END TRY
	BEGIN CATCH
		ROLLBACK TRAN
