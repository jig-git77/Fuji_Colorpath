IF EXISTS (SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='SpotTargetChartSetting' AND TABLE_SCHEMA='CPSpot' AND COLUMN_NAME='IsCustom')
BEGIN
	ALTER TABLE CPSpot.SpotTargetChartSetting 
		DROP COLUMN  IsCustom;
END
GO

IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='SpotTarget' AND TABLE_SCHEMA='CPSpot' AND COLUMN_NAME='IsCustom')
BEGIN
	ALTER TABLE CPSpot.SpotTarget 
		Add IsCustom BIT;
END
GO

UPDATE CPSpot.SpotTarget
	SET IsCustom = 0;
GO



