ALTER PROCEDURE [CP].[InsertDeviceFamily]  
 
 @DeviceFamilyDesc	NVARCHAR(25)
,@IsSupportCloudFlow BIT
,@IsActive	BIT
  
AS  
BEGIN  
   IF EXISTS (SELECT * FROM CP.DeviceFamily Where Upper(DeviceFamilyDesc) = Upper(@DeviceFamilyDesc))  
	BEGIN  
		Return -1
	END 
 BEGIN TRY
		BEGIN TRAN

  INSERT INTO CP.DeviceFamily
   (  
		 DeviceFamilyDesc
		,IsSupportCloudFlow
		,IsActive
   )  
  VALUES   
   (  
		 @DeviceFamilyDesc
		,@IsSupportCloudFlow
		,@IsActive
   )     
  
  COMMIT TRAN
	END TRY
	BEGIN CATCH
		ROLLBACK TRAN
  DECLARE @ERROR_NUMBER INT   
  DECLARE @ERROR_SEVERITY INT  
  DECLARE @ERROR_STATE INT   
  DECLARE @ERROR_PROCEDURE NVARCHAR(252)   
  DECLARE @ERROR_LINE INT   
  DECLARE @ERROR_MESSAGE NVARCHAR(4000)   
  SELECT @ERROR_NUMBER = ERROR_NUMBER()  , @ERROR_NUMBER = ERROR_NUMBER() , @ERROR_SEVERITY = ERROR_SEVERITY() , @ERROR_STATE = ERROR_STATE() , @ERROR_PROCEDURE = ERROR_PROCEDURE() , @ERROR_LINE = ERROR_LINE() , @ERROR_MESSAGE = ERROR_MESSAGE()   
  EXEC InsertSQLErrorLog @ERROR_NUMBER , @ERROR_SEVERITY , @ERROR_STATE , @ERROR_PROCEDURE , @ERROR_LINE , @ERROR_MESSAGE   
  RAISERROR(@ERROR_MESSAGE,@ERROR_SEVERITY,@ERROR_STATE) /******Raise Error backto client *****/   
 END CATCH  
  
END



